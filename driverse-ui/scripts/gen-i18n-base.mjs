#!/usr/bin/env node
/**
 * gen-i18n-base.mjs — regenerates src/i18n/{en_US,es_ES}.json.
 *
 * Both apps ship a `sys.json` per locale. The overlap is large but not total, and a handful of shared
 * keys carry different copy. This script emits the intersection — keys present in BOTH apps, for BOTH
 * locales — as the library's base bundle. Apps keep their own files and merge the base underneath, so
 * an app key always wins over a library key.
 *
 * Value conflicts resolve to Business, and every one of them is listed in the generated header so the
 * divergence stays visible rather than silently picking a winner.
 *
 * Run: node scripts/gen-i18n-base.mjs
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const LIB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PROGRAM = path.join(LIB, "..");
const OUT_DIR = path.join(LIB, "src", "i18n");

const APPS = {
	A: path.join(PROGRAM, "spike_Driverse_FE_Autocredit-qa", "src", "locales", "lang"),
	B: path.join(PROGRAM, "spike_Driverse_FE_Business-dev", "src", "locales", "lang"),
};
const LOCALES = ["en_US", "es_ES"];

/** { a: { b: "x" } } -> { "a.b": "x" } */
function flatten(obj, prefix = "", out = {}) {
	for (const [key, value] of Object.entries(obj ?? {})) {
		const next = prefix ? `${prefix}.${key}` : key;
		if (value && typeof value === "object" && !Array.isArray(value)) flatten(value, next, out);
		else out[next] = value;
	}
	return out;
}

/** { "a.b": "x" } -> { a: { b: "x" } } */
function nest(flat) {
	const out = {};
	for (const [key, value] of Object.entries(flat)) {
		const parts = key.split(".");
		let cursor = out;
		for (const part of parts.slice(0, -1)) {
			cursor[part] ??= {};
			cursor = cursor[part];
		}
		cursor[parts.at(-1)] = value;
	}
	return out;
}

const readSys = (root, locale) => {
	const file = path.join(root, locale, "sys.json");
	if (!fs.existsSync(file)) return null;
	return flatten(JSON.parse(fs.readFileSync(file, "utf8")));
};

const sources = {};
for (const [app, root] of Object.entries(APPS)) {
	for (const locale of LOCALES) {
		const flat = readSys(root, locale);
		if (!flat) {
			console.error(`Missing ${locale}/sys.json under ${root}`);
			process.exit(1);
		}
		sources[`${app}:${locale}`] = flat;
	}
}

const isUsable = (value) => typeof value === "string" && value.trim() !== "";

// A key belongs in the base bundle only if both apps give it a non-empty string in both locales.
// (`sys.login.signInTitle` is empty in both apps, so it is dropped rather than shipped blank.)
const sharedKeys = Object.keys(sources["A:en_US"])
	.filter((key) =>
		LOCALES.every((locale) => isUsable(sources[`A:${locale}`][key]) && isUsable(sources[`B:${locale}`][key])),
	)
	.sort();

const conflicts = [];
const bundles = Object.fromEntries(LOCALES.map((locale) => [locale, {}]));

for (const key of sharedKeys) {
	for (const locale of LOCALES) {
		const a = sources[`A:${locale}`][key];
		const b = sources[`B:${locale}`][key];
		if (a !== b) conflicts.push({ locale, key, a, b });
		// Business wins; see the header note in src/i18n/index.ts.
		bundles[locale][key] = b;
	}
}

fs.mkdirSync(OUT_DIR, { recursive: true });
for (const locale of LOCALES) {
	fs.writeFileSync(path.join(OUT_DIR, `${locale}.json`), `${JSON.stringify(nest(bundles[locale]), null, "\t")}\n`);
}

// The full conflict list is long (mostly es_ES phrasing), so it goes to a doc rather than a header.
const byLocale = LOCALES.map((locale) => `${conflicts.filter((c) => c.locale === locale).length} ${locale}`).join(", ");
const conflictDoc = `# i18n base bundle — shared keys with divergent copy

> Generated by \`scripts/gen-i18n-base.mjs\`. ${conflicts.length} of ${sharedKeys.length} shared keys differ (${byLocale}).
> The library ships Business's wording. Reconcile these deliberately, then re-run the script.

| Locale | Key | Autocredit | Business |
|---|---|---|---|
${conflicts
	.map(
		(c) =>
			`| ${c.locale} | \`${c.key}\` | ${String(c.a).replace(/\|/g, "\\|")} | ${String(c.b).replace(/\|/g, "\\|")} |`,
	)
	.join("\n")}
`;
fs.mkdirSync(path.join(LIB, "docs"), { recursive: true });
fs.writeFileSync(path.join(LIB, "docs", "i18n-conflicts.md"), conflictDoc);

const index = `/** @lib-native */

/**
 * GENERATED bundles, hand-written helper. Run \`node scripts/gen-i18n-base.mjs\` to refresh the JSON.
 *
 * The base translation bundle: every \`sys.*\` key both apps define in both locales — ${sharedKeys.length} keys.
 * App-specific keys stay in the apps, and \`mergeLibI18n\` never overwrites them.
 *
 * ${conflicts.length} shared key(s) carry different copy between the two apps (${byLocale}) — almost all of it
 * es_ES phrasing drift. Business's wording is used; every divergence is tabulated in
 * docs/i18n-conflicts.md so it can be reconciled deliberately rather than silently.
 */
import type { i18n as I18nInstance } from "i18next";
import en_US from "./en_US.json";
import es_ES from "./es_ES.json";

export { en_US, es_ES };

export const baseResources = { en_US, es_ES } as const;

export type BaseLocale = keyof typeof baseResources;

/**
 * Adds the library's base bundle to an existing i18next instance. The bundle keeps the \`sys\` root the
 * apps' sys.json files have and goes into i18next's default \`translation\` namespace, which is where both
 * apps spread theirs — so \`t("sys.api.errorTip")\` resolves unchanged.
 * Deep-merged and non-destructive: \`addResourceBundle(..., deep, overwrite=false)\` means an app key
 * always wins over the library's.
 *
 * @example
 * import i18n from "@/locales/i18n";
 * mergeLibI18n(i18n);
 */
export function mergeLibI18n(i18n: I18nInstance, namespace = "translation"): void {
	for (const [locale, resources] of Object.entries(baseResources)) {
		i18n.addResourceBundle(locale, namespace, resources, /* deep */ true, /* overwrite */ false);
	}
}
`;

fs.writeFileSync(path.join(OUT_DIR, "index.ts"), index);
console.log(
	`i18n base: ${sharedKeys.length} shared keys across ${LOCALES.length} locales; ${conflicts.length} value conflict(s) resolved to Business`,
);
